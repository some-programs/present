// Readmegen writes README.md from the doc comments of the present command
// and the present package.
//
// It is run by go generate from the module root:
//
//	go generate
//
// With -site, it writes the pages of the GitHub Pages site to the given
// directory instead: index.html, the same content as README.md, and
// examples/index.html, a list of the example presentations. They go with the
// examples and style sheets that present export writes to the directory:
//
//	go run . export -source -o _site examples/*.slide examples/*.article
//	go run ./internal/readmegen -site _site
package main

import (
	"bytes"
	_ "embed"
	"flag"
	"go/ast"
	"go/doc"
	"go/doc/comment"
	"go/parser"
	"go/token"
	"html/template"
	"log"
	"os"
	"path/filepath"
	"strings"

	"github.com/some-programs/present/internal/readme"
	"github.com/some-programs/present/pkg/present"
)

// generated marks README.md as generated, ahead of header.md.
const generated = "<!-- Code generated by internal/readmegen from internal/readmegen/header.md, doc.go and pkg/present/doc.go. DO NOT EDIT. -->\n\n"

// header is the start of README.md, before the sections generated from the
// doc comments.
//
//go:embed header.md
var header []byte

// pageTmpl is the template of the pages that -site writes, executed with a
// pageData.
//
//go:embed page.tmpl
var pageTmpl string

// examplesTmpl is the template of the body of the examples page, executed
// with an examplesData.
//
//go:embed examples.tmpl
var examplesTmpl string

func main() {
	log.SetFlags(0)
	log.SetPrefix("readmegen: ")
	site := flag.String("site", "", "write the GitHub Pages site to `dir` instead of README.md")
	flag.Parse()

	var buf bytes.Buffer
	buf.WriteString(generated)
	buf.Write(header)
	buf.WriteString("## Command\n\n")
	buf.Write(markdown("doc.go", "github.com/some-programs/present"))
	buf.WriteString("\n## File format\n\n")
	buf.Write(markdown("pkg/present/doc.go", "github.com/some-programs/present/pkg/present"))

	if *site != "" {
		writeSite(*site, buf.Bytes())
		return
	}
	if err := os.WriteFile("README.md", buf.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}

// pageData is what page.tmpl is executed with.
type pageData struct {
	Title string
	Root  string // the relative URL of the site root, ending in a slash
	Home  string // the link of the heading
	Body  template.HTML
}

// examplesData is what examples.tmpl is executed with.
type examplesData struct {
	Slides, Articles []example
}

// An example is an exported example presentation.
type example struct {
	Name  string // the file name of its source, such as intro.slide
	Path  string // its page, relative to the examples page
	Title string
}

// writeSite writes the pages of the GitHub Pages site to dir: the README
// src, with its links to the examples pointing at their exported pages, and
// the list of the examples.
func writeSite(dir string, src []byte) {
	page := template.Must(template.New("page").Parse(pageTmpl))
	write := func(name string, data pageData) {
		var b bytes.Buffer
		if err := page.Execute(&b, data); err != nil {
			log.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(dir, name), b.Bytes(), 0o644); err != nil {
			log.Fatal(err)
		}
	}

	body, err := readme.Render(src, "examples")
	if err != nil {
		log.Fatal(err)
	}
	write("index.html", pageData{
		Title: "present",
		Home:  "https://github.com/some-programs/present",
		Body:  body,
	})

	var data examplesData
	for _, ext := range []string{".slide", ".article"} {
		files, err := filepath.Glob(filepath.Join("examples", "*"+ext))
		if err != nil {
			log.Fatal(err)
		}
		for _, file := range files {
			f, err := os.Open(file)
			if err != nil {
				log.Fatal(err)
			}
			doc, err := present.Parse(f, file, present.TitlesOnly)
			f.Close()
			if err != nil {
				log.Fatal(err)
			}
			name := filepath.Base(file)
			e := example{Name: name, Path: strings.TrimSuffix(name, ext) + ".html", Title: doc.Title}
			if ext == ".slide" {
				data.Slides = append(data.Slides, e)
			} else {
				data.Articles = append(data.Articles, e)
			}
		}
	}
	var b bytes.Buffer
	if err := template.Must(template.New("examples").Parse(examplesTmpl)).Execute(&b, data); err != nil {
		log.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Join(dir, "examples"), 0o755); err != nil {
		log.Fatal(err)
	}
	write(filepath.Join("examples", "index.html"), pageData{
		Title: "Examples - present",
		Root:  "../",
		Home:  "../",
		Body:  template.HTML(b.String()),
	})
}

// markdown returns the package doc comment in file as Markdown, with its
// headings one level below the README's section headings. Heading IDs are
// omitted because GitHub renders the {#id} syntax as text.
func markdown(file, importPath string) []byte {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, file, nil, parser.ParseComments)
	if err != nil {
		log.Fatal(err)
	}
	pkg, err := doc.NewFromFiles(fset, []*ast.File{f}, importPath)
	if err != nil {
		log.Fatal(err)
	}
	p := pkg.Printer()
	p.HeadingLevel = 3
	p.HeadingID = func(*comment.Heading) string { return "" }
	return p.Markdown(pkg.Parser().Parse(pkg.Doc))
}
