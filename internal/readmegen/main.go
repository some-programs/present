// Readmegen writes README.md from the doc comments of the present command
// and the present package.
//
// It is run by go generate from the module root:
//
//	go generate
package main

import (
	"bytes"
	_ "embed"
	"go/ast"
	"go/doc"
	"go/doc/comment"
	"go/parser"
	"go/token"
	"log"
	"os"
)

// generated marks README.md as generated, ahead of header.md.
const generated = "<!-- Code generated by internal/readmegen from internal/readmegen/header.md, doc.go and pkg/present/doc.go. DO NOT EDIT. -->\n\n"

// header is the start of README.md, before the sections generated from the
// doc comments.
//
//go:embed header.md
var header []byte

func main() {
	log.SetFlags(0)
	log.SetPrefix("readmegen: ")

	var buf bytes.Buffer
	buf.WriteString(generated)
	buf.Write(header)
	buf.WriteString("## Command\n\n")
	buf.Write(markdown("doc.go", "github.com/some-programs/present"))
	buf.WriteString("\n## File format\n\n")
	buf.Write(markdown("pkg/present/doc.go", "github.com/some-programs/present/pkg/present"))

	if err := os.WriteFile("README.md", buf.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}

// markdown returns the package doc comment in file as Markdown, with its
// headings one level below the README's section headings. Heading IDs are
// omitted because GitHub renders the {#id} syntax as text.
func markdown(file, importPath string) []byte {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, file, nil, parser.ParseComments)
	if err != nil {
		log.Fatal(err)
	}
	pkg, err := doc.NewFromFiles(fset, []*ast.File{f}, importPath)
	if err != nil {
		log.Fatal(err)
	}
	p := pkg.Printer()
	p.HeadingLevel = 3
	p.HeadingID = func(*comment.Heading) string { return "" }
	return p.Markdown(pkg.Parser().Parse(pkg.Doc))
}
