// Readmegen writes README.md from the doc comments of the present command
// and the present package.
//
// It is run by go generate from the module root:
//
//	go generate
package main

import (
	"bytes"
	"go/ast"
	"go/doc"
	"go/doc/comment"
	"go/parser"
	"go/token"
	"log"
	"os"
)

const header = `<!-- Code generated by internal/readmegen from doc.go and pkg/present/doc.go. DO NOT EDIT. -->

# present

[![Go Reference](https://pkg.go.dev/badge/github.com/some-programs/present.svg)](https://pkg.go.dev/github.com/some-programs/present)

Present is a simple presentation tool: slides and articles are written as
plain text files with Markdown, and shown in the browser.

It is based on [golang.org/x/tools/cmd/present](https://pkg.go.dev/golang.org/x/tools/cmd/present).
It started as a verbatim copy of it at commit
[a3af45f248c005a2f2485ca99ad978547753a17c](https://go.googlesource.com/tools/+/a3af45f248c005a2f2485ca99ad978547753a17c)
("internal/refactor/inline: reduce void calls in tail position").

The quickest way to learn present is to look at the [examples](examples):
presentations that show every feature, from Markdown text and speaker notes
to runnable code, diagrams and video. They are built into present, so one
line downloads and runs the latest version and shows them along with this
documentation:

    go run github.com/some-programs/present@latest -doc -notes

Then open http://127.0.0.1:3999. The index lists the presentations in the
current directory, below links to the documentation and the examples. From a
checkout of this repository, run

    go run . -content examples -notes

to show the examples there instead.

`

func main() {
	log.SetFlags(0)
	log.SetPrefix("readmegen: ")

	var buf bytes.Buffer
	buf.WriteString(header)
	buf.WriteString("## Command\n\n")
	buf.Write(markdown("doc.go", "github.com/some-programs/present"))
	buf.WriteString("\n## File format\n\n")
	buf.Write(markdown("pkg/present/doc.go", "github.com/some-programs/present/pkg/present"))

	if err := os.WriteFile("README.md", buf.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}

// markdown returns the package doc comment in file as Markdown, with its
// headings one level below the README's section headings. Heading IDs are
// omitted because GitHub renders the {#id} syntax as text.
func markdown(file, importPath string) []byte {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, file, nil, parser.ParseComments)
	if err != nil {
		log.Fatal(err)
	}
	pkg, err := doc.NewFromFiles(fset, []*ast.File{f}, importPath)
	if err != nil {
		log.Fatal(err)
	}
	p := pkg.Printer()
	p.HeadingLevel = 3
	p.HeadingID = func(*comment.Heading) string { return "" }
	return p.Markdown(pkg.Parser().Parse(pkg.Doc))
}
